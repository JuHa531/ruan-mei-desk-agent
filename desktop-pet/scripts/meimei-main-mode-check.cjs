'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.connectOverCDP('http://127.0.0.1:9223');
 const page=browser.contexts().flatMap(c=>c.pages()).find(p=>p.url().includes('127.0.0.1:7788'));
 assert.ok(page,'Main MeiMei window');
 await page.waitForFunction(()=>typeof window.pywebview?.api?.pet_toggle==='function');
 const before=await page.locator('#log').innerText();
 await page.locator('#petMode').click();
 assert.equal(await page.locator('#petPanel').evaluate(n=>n.open),true);
 let state=await page.evaluate(()=>window.pywebview.api.pet_status());
 if(!state.enabled)await page.locator('#petModeToggle').click();
 await page.waitForFunction(async()=>{const state=await window.pywebview.api.pet_status();return state.enabled&&state.ready;},null,{timeout:30000});
 await page.locator('#petModePercent').fill('75');await page.locator('#petModeSizeForm button[type=submit]').click();
 await page.waitForFunction(async()=>(await window.pywebview.api.pet_status()).scale===.75);
 await page.evaluate(()=>petModeCall('pet_status'));
 await page.screenshot({path:path.resolve(__dirname,'../artifacts/meimei-integrated-controls.png')});
 await page.locator('#petModeSettings').click();
 await page.locator('#petModeToggle').click();
 await page.waitForFunction(async()=>(await window.pywebview.api.pet_status()).enabled===false);
 await page.locator('#petModeToggle').click();
 await page.waitForFunction(async()=>(await window.pywebview.api.pet_status()).ready===true);
 await page.evaluate(()=>window.pywebview.api.pet_resize(100));
 assert.equal(await page.locator('#log').innerText(),before,'Pet mode preserves current conversation');
 fs.writeFileSync(path.resolve(__dirname,'../artifacts/meimei-integrated-controls.json'),JSON.stringify({mainAppBridge:true,realToggle:true,resize:true,settings:true,existingConversationPreserved:true,readyBeforeOwnerClose:true}));
 await page.evaluate(()=>window.pywebview.api.close()).catch(()=>{});
 await browser.close().catch(()=>{});console.log('MeiMei built-in controls passed; owner closed.');
})().catch(e=>{console.error(e);process.exitCode=1;});
